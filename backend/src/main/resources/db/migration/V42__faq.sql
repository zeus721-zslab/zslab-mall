--   공개 목록·즉시 답은 visible = 1 AND deleted_at IS NULL 전량(수십~수백 건)을 읽어 앱이 정렬·점수화한다. 인덱스는 카테고리 안 정렬·
--   다음 순번 계산(MAX(sort_order) WHERE category = ?)용이다.
-- 초기 데이터: 운영 기본 콘텐츠(데모 데이터 아님)라 이 마이그레이션이 넣는다. 답변은 구현 동작 기준이다.
--   이후 관리자 수정분과 이 파일 원문은 달라질 수 있다
--   (마이그레이션은 재실행되지 않는다).
-- 데이터 안전: 신규 테이블 1개 + 초기 FAQ INSERT — 기존 행 변경 없음.

CREATE TABLE faq (
  id              BIGINT        NOT NULL AUTO_INCREMENT,
  category        VARCHAR(30)   NOT NULL COMMENT '카테고리(ORDER_PAYMENT·DELIVERY·CLAIM·ACCOUNT·REVIEW_QUESTION)',
  question        VARCHAR(200)  NOT NULL COMMENT '질문',
  answer          VARCHAR(2000) NOT NULL COMMENT '답변(평문)',
  sort_order      INT           NOT NULL COMMENT '카테고리 안 노출 순서(0부터)',
  visible         BOOLEAN       NOT NULL COMMENT '공개 여부',
  created_at      DATETIME(6)   NOT NULL,
  created_by      BIGINT        NULL,
  updated_at      DATETIME(6)   NOT NULL,
  updated_by      BIGINT        NULL,
  deleted_at      DATETIME(6)   NULL,
  deleted_by      BIGINT        NULL,
  delete_reason   VARCHAR(255)  NULL,
  PRIMARY KEY (id),
  KEY ix_faq_category_sort (category, sort_order),
  CONSTRAINT chk_faq_category CHECK (category IN ('ORDER_PAYMENT','DELIVERY','CLAIM','ACCOUNT','REVIEW_QUESTION'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='구매자 채팅 도우미 FAQ(SOFT·Track 106-3)';

