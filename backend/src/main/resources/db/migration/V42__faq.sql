--         FE 상수. 카테고리 사이 순서는 Java enum 선언 순서(칩 순서)이고 sort_order는 카테고리 안 순서다(0부터).
--         visible = 공개 여부(관리자 숨김은 사유 없이 토글 — 운영자 자기 콘텐츠). 삭제는 soft delete(deleted_at · Category 선례).
